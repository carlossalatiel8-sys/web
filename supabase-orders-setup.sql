-- Crea un pedido de forma segura. El servidor vuelve a calcular artículos,
-- cantidades y total desde store_products, y el token evita duplicados por doble clic.
create or replace function public.create_store_order(
  p_items jsonb,
  p_payment_method text,
  p_checkout_token uuid default null
)
returns table (
  id uuid,
  order_code text,
  total_mxn integer,
  status text
)
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_user_id uuid := auth.uid();
  v_input_count integer;
  v_match_count integer;
  v_items jsonb;
  v_total integer;
  v_email text;
  v_name text;
  v_order public.orders%rowtype;
begin
  if v_user_id is null then
    raise exception 'Debes iniciar sesión para crear un pedido.' using errcode = '42501';
  end if;

  if p_payment_method not in ('bank_transfer', 'paypal') then
    raise exception 'Método de pago no permitido.' using errcode = '22023';
  end if;

  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'El carrito está vacío.' using errcode = '22023';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_items) as input(product_id text, quantity integer)
    where input.product_id is null or input.quantity is null or input.quantity < 1 or input.quantity > 10
  ) then
    raise exception 'La cantidad de un producto no es válida.' using errcode = '22023';
  end if;

  if exists (
    with requested as (
      select product_id, sum(quantity)::integer as quantity
      from jsonb_to_recordset(p_items) as input(product_id text, quantity integer)
      group by product_id
    ) select 1 from requested where quantity > 10
  ) then
    raise exception 'No puedes comprar más de 10 unidades del mismo producto.' using errcode = '22023';
  end if;

  -- Si un clic se reintenta por conexión lenta, devuelve el mismo pedido.
  if p_checkout_token is not null then
    select * into v_order
    from public.orders
    where user_id = v_user_id and checkout_token = p_checkout_token;
    if found then
      return query select v_order.id, v_order.order_code, v_order.total_mxn, v_order.status;
      return;
    end if;
  end if;

  with requested as (
    select product_id, sum(quantity)::integer as quantity
    from jsonb_to_recordset(p_items) as input(product_id text, quantity integer)
    group by product_id
  )
  select count(*) into v_input_count from requested;

  with requested as (
    select product_id, sum(quantity)::integer as quantity
    from jsonb_to_recordset(p_items) as input(product_id text, quantity integer)
    group by product_id
  )
  select count(*) into v_match_count
  from requested r
  join public.store_products p on p.id = r.product_id and p.active = true;

  if v_input_count <> v_match_count then
    raise exception 'Uno o más productos ya no están disponibles.' using errcode = '22023';
  end if;

  with requested as (
    select product_id, sum(quantity)::integer as quantity
    from jsonb_to_recordset(p_items) as input(product_id text, quantity integer)
    group by product_id
  )
  select
    jsonb_agg(
      jsonb_build_object(
        'product_id', p.id,
        'name', p.name,
        'unit_price_mxn', p.price_mxn,
        'quantity', r.quantity,
        'line_total_mxn', p.price_mxn * r.quantity
      ) order by p.name
    ),
    sum(p.price_mxn * r.quantity)::integer
  into v_items, v_total
  from requested r
  join public.store_products p on p.id = r.product_id and p.active = true;

  select email into v_email from auth.users where id = v_user_id;
  select username into v_name from public.profiles where id = v_user_id;
  v_name := coalesce(v_name, split_part(coalesce(v_email, 'cliente'), '@', 1));

  insert into public.orders (
    user_id, customer_email, customer_name, items, total_mxn,
    payment_method, status, checkout_token
  ) values (
    v_user_id, coalesce(v_email, ''), v_name, v_items, v_total,
    p_payment_method, 'pending_payment', p_checkout_token
  ) returning * into v_order;

  return query select v_order.id, v_order.order_code, v_order.total_mxn, v_order.status;
end;
$$;

grant execute on function public.create_store_order(jsonb, text, uuid) to authenticated;

-- Guarda la ruta del comprobante y cambia únicamente el pedido propio de
-- pendiente de pago a pendiente de validación.
create or replace function public.submit_bank_receipt(
  p_order_id uuid,
  p_receipt_path text
)
returns table (
  id uuid,
  order_code text,
  status text
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_order public.orders%rowtype;
begin
  if v_user_id is null then
    raise exception 'Debes iniciar sesión.' using errcode = '42501';
  end if;

  if p_receipt_path is null
    or p_receipt_path !~ ('^' || v_user_id::text || '/' || p_order_id::text || '/') then
    raise exception 'La ruta del comprobante no es válida.' using errcode = '22023';
  end if;

  update public.orders
  set receipt_path = p_receipt_path,
      status = 'pending_validation',
      updated_at = now()
  where id = p_order_id
    and user_id = v_user_id
    and payment_method = 'bank_transfer'
    and status = 'pending_payment'
  returning * into v_order;

  if not found then
    raise exception 'Este pedido no puede recibir un comprobante.' using errcode = '22023';
  end if;

  return query select v_order.id, v_order.order_code, v_order.status;
end;
$$;

grant execute on function public.submit_bank_receipt(uuid, text) to authenticated;

