drop policy if exists "Products are visible to everyone" on public.store_products;
create policy "Products are visible to everyone"
on public.store_products for select
to anon, authenticated
using (active = true);

-- Cada cliente sólo puede ver sus propios pedidos. No hay políticas de insertar,
-- modificar o borrar desde el navegador: eso se realiza con funciones controladas.
drop policy if exists "Users can read their own orders" on public.orders;
create policy "Users can read their own orders"
on public.orders for select
to authenticated
using (auth.uid() = user_id);

-- Arquitectura preparada para un panel futuro: asigna app_metadata.role = admin
-- desde un entorno seguro antes de mostrarle dicho panel a una persona.
create or replace function public.is_store_admin()
returns boolean
language sql
stable
as $$
  select coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin', false);
$$;

drop policy if exists "Admins can manage orders" on public.orders;
create policy "Admins can manage orders"
on public.orders for all
to authenticated
using (public.is_store_admin())
with check (public.is_store_admin());

