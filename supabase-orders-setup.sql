create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity (start with 1001) unique not null,
  order_code text unique,
  user_id uuid not null references auth.users(id) on delete restrict,
  customer_email text not null,
  customer_name text not null,
  items jsonb not null check (jsonb_typeof(items) = 'array' and jsonb_array_length(items) > 0),
  total_mxn integer not null check (total_mxn >= 0),
  payment_method text not null check (payment_method in ('bank_transfer', 'paypal')),
  status text not null default 'pending_payment' check (status in (
    'pending_payment',
    'pending_validation',
    'payment_approved',
    'payment_rejected',
    'cancelled',
    'delivered'
  )),
  receipt_path text,
  paypal_order_id text unique,
  paypal_capture_id text,
  checkout_token uuid unique,
  download_links jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  paid_at timestamptz,
  delivered_at timestamptz
);

-- Bitácora interna para que un doble clic o reintento no mande correos duplicados.
create table if not exists public.order_notifications (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  event text not null check (event in ('bank_receipt', 'paypal_approved')),
  sent_at timestamptz not null default now(),
  unique (order_id, event)
);

-- Convierte el número interno en el código visible del cliente: PED-1001.
create or replace function public.set_order_code()
returns trigger
language plpgsql
as $$
begin
  if new.order_code is null then
    new.order_code := 'PED-' || lpad(new.order_number::text, 4, '0');
  end if;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists set_order_code_before_insert on public.orders;
create trigger set_order_code_before_insert
before insert or update on public.orders
for each row execute procedure public.set_order_code();

create index if not exists orders_user_created_idx on public.orders (user_id, created_at desc);
create index if not exists orders_status_created_idx on public.orders (status, created_at desc);

